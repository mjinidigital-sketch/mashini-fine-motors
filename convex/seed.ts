export const seed = internalMutation({
  args: {},
  handler: async (ctx) => {
    // First, create a seed user if none exists
    const existingUsers = await ctx.db.query("users").take(1);
    let userId: Id<"users">;
    
    if (existingUsers.length === 0) {
      userId = await ctx.db.insert("users", {
        name: "Car Marketplace Admin",
        email: "admin@carmarketplace.com",
        role: "dealer",
        isDealer: true,
        dealershipName: "Car Marketplace Dealership",
        location: "Nairobi",
        createdAt: Date.now(),
        updatedAt: Date.now(),
      });
    } else {
      userId = existingUsers[0]._id;
    }

    // Clear existing vehicles for idempotency
    const existingVehicles = await ctx.db.query("vehicles").collect();
    for (const vehicle of existingVehicles) {
      await ctx.db.delete(vehicle._id);
    }

    // Insert 100 vehicles
    const now = Date.now();
    for (const car of CARS_DATA) {
      await ctx.db.insert("vehicles", {
        ...car,
        userId,
        thumbnailUrl: car.images[0],
        createdAt: now,
        updatedAt: now,
      });
    }

    return { 
      message: `Seeded ${CARS_DATA.length} vehicles successfully`,
      userId 
    };
  },
});
